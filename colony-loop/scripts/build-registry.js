#!/usr/bin/env node
// Build colony-loop/agents/registry.js from the current contents of
// colony-loop/agents/*.js. Each file becomes one entry:
//   filename: foo_bar.js  →  signal_type: 'FOO_BAR'  →  path: './foo_bar.js'
//
// Validates that every file exports a `run` function before adding it
// to the registry. Files that don't export run() are skipped with a
// loud warning — they're either work-in-progress stubs or buggy
// (which is what we want the registry to catch).
//
// Run: node colony-loop/scripts/build-registry.js
//
// Output: colony-loop/agents/registry.js  (commit this)

import { readdirSync, writeFileSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const AGENTS_DIR = join(HERE, '..', 'agents');
const OUTPUT = join(AGENTS_DIR, 'registry.js');

function filenameToSignalType(filename) {
  // strip .js extension, uppercase
  return filename.replace(/\.js$/i, '').toUpperCase();
}

const files = readdirSync(AGENTS_DIR)
  .filter((f) => f.endsWith('.js') && f !== 'registry.js');

const entries = [];
const skipped = [];

for (const file of files) {
  const path = join(AGENTS_DIR, file);
  let stats;
  try { stats = statSync(path); } catch (e) { skipped.push({ file, reason: 'stat failed' }); continue; }
  if (stats.size === 0) { skipped.push({ file, reason: 'empty' }); continue; }

  // Validate the file exports run() — import it
  let mod;
  try {
    mod = await import(`file://${path}`);
  } catch (e) {
    skipped.push({ file, reason: 'import error: ' + e.message.slice(0, 100) });
    continue;
  }
  if (typeof mod.run !== 'function') {
    skipped.push({ file, reason: 'no run() export' });
    continue;
  }

  entries.push({
    signal_type: filenameToSignalType(file),
    relative_path: './' + file,
    source_file: file,
  });
}

// Sort by signal_type alphabetically for stable diff
entries.sort((a, b) => a.signal_type.localeCompare(b.signal_type));

const header = `// AUTO-GENERATED by scripts/build-registry.js. DO NOT EDIT BY HAND.
//
// Explicit signal_type → agent file map. Replaces the old
// "lowercase signal_type → filename" implicit convention that silently
// no-fired when filenames drifted from signal types.
//
// To add a new agent:
//   1. Create the .js file in agents/
//   2. Re-run: node colony-loop/scripts/build-registry.js
//   3. Commit the regenerated registry.js
//
// To rename: update the signal_type emitter, then regenerate.
//
// Generated: ${new Date().toISOString()}
// Total registered: ${entries.length}
// Skipped (no run() or import error): ${skipped.length}

export const AGENT_REGISTRY = {
${entries.map((e) => `  '${e.signal_type}': '${e.relative_path}',`).join('\n')}
};

export const SKIPPED_FILES = ${JSON.stringify(skipped, null, 2)};
`;

writeFileSync(OUTPUT, header);

console.log(`Registry written: ${OUTPUT}`);
console.log(`  Registered: ${entries.length}`);
console.log(`  Skipped:    ${skipped.length}`);
if (skipped.length > 0) {
  console.log('Skipped files:');
  for (const s of skipped.slice(0, 20)) {
    console.log(`    ${s.file} — ${s.reason}`);
  }
  if (skipped.length > 20) console.log(`    ... and ${skipped.length - 20} more`);
}
