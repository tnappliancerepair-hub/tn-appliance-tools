#!/usr/bin/env node
// One-shot fix for the architect's filename/signal mismatch bug.
// Walks every architect-generated agent in colony-loop/agents/, reads its
// "// Signal in: SIGNAL_TYPE" header comment, lowercases that into the
// expected filename, and `git mv`s it into place when they differ.
//
// Run once after the template generators were producing the wrong filenames.
// Idempotent: agents already matching their signal_type are skipped.

import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';

const AGENTS_DIR = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../agents');

const SIGNAL_RE = /^\/\/\s*Signal in:\s*([A-Z0-9_]+)\s*$/m;
const ARCH_RE = /^\/\/\s*Auto-generated by colony_architect/m;

const summary = {
  total_scanned: 0,
  architect_built: 0,
  already_correct: 0,
  renamed: 0,
  no_signal_in: 0,
  collisions: 0,
  errors: [],
  renames: [],
};

const files = fs.readdirSync(AGENTS_DIR).filter((f) => f.endsWith('.js'));
for (const file of files) {
  summary.total_scanned += 1;
  const full = path.join(AGENTS_DIR, file);
  const text = fs.readFileSync(full, 'utf8');
  if (!ARCH_RE.test(text)) continue;
  summary.architect_built += 1;

  const m = text.match(SIGNAL_RE);
  if (!m) {
    summary.no_signal_in += 1;
    continue;
  }
  const sig = m[1].toLowerCase();
  const expected = sig + '.js';
  if (file === expected) {
    summary.already_correct += 1;
    continue;
  }

  const target = path.join(AGENTS_DIR, expected);
  if (fs.existsSync(target)) {
    summary.collisions += 1;
    summary.errors.push({ file, target: expected, reason: 'target_exists' });
    continue;
  }

  try {
    execSync(`git mv "${full}" "${target}"`, { stdio: 'pipe' });
    summary.renamed += 1;
    summary.renames.push({ from: file, to: expected });
  } catch (err) {
    // Fall back to plain rename when git can't move (e.g. untracked).
    try {
      fs.renameSync(full, target);
      summary.renamed += 1;
      summary.renames.push({ from: file, to: expected, mode: 'fs' });
    } catch (err2) {
      summary.errors.push({ file, target: expected, error: String(err2.message || err2) });
    }
  }
}

console.log(`scanned=${summary.total_scanned} arch=${summary.architect_built} already_correct=${summary.already_correct} renamed=${summary.renamed} no_signal=${summary.no_signal_in} collisions=${summary.collisions} errors=${summary.errors.length}`);
if (summary.errors.length) {
  for (const e of summary.errors) console.log('ERR', JSON.stringify(e));
}
